"use client";

import React, { useState, useEffect } from "react";
import { Play, Pause, Trash2, RefreshCw, Sparkles, Volume2, CheckCircle2, AlertCircle } from "lucide-react";

interface RadioDropItem {
  id: number;
  persona: string;
  mood: string;
  title: string;
  script: string;
  audio_url: string;
  timing_type: string;
  created_at: string;
}

export default function DropManagerPanel() {
  const [drops, setDrops] = useState<RadioDropItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [currentlyPlayingId, setCurrentlyPlayingId] = useState<number | null>(null);
  const [audioElement, setAudioElement] = useState<HTMLAudioElement | null>(null);
  const [feedback, setFeedback] = useState<{ text: string; type: "success" | "error" } | null>(null);

  const showFeedback = (text: string, type: "success" | "error") => {
    setFeedback({ text, type });
    setTimeout(() => setFeedback(null), 4000);
  };

  const fetchDrops = async () => {
    try {
      setLoading(true);
      const res = await fetch("/api/admin/radio/drops");
      if (res.ok) {
        const data = await res.json();
        setDrops(data.drops || []);
      }
    } catch (err: any) {
      showFeedback("Failed to load drops: " + err.message, "error");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchDrops();
  }, []);

  const handlePlayToggle = (drop: RadioDropItem) => {
    if (!drop.audio_url) {
      showFeedback("Audio file not available for this drop (synthesis pending or mock)", "error");
      return;
    }

    if (currentlyPlayingId === drop.id && audioElement) {
      audioElement.pause();
      setCurrentlyPlayingId(null);
      return;
    }

    if (audioElement) {
      audioElement.pause();
    }

    const audio = new Audio(drop.audio_url);
    audio.onended = () => setCurrentlyPlayingId(null);
    audio.onerror = () => {
      showFeedback("Failed to play drop audio", "error");
      setCurrentlyPlayingId(null);
    };

    audio.play().then(() => {
      setAudioElement(audio);
      setCurrentlyPlayingId(drop.id);
    }).catch(() => {
      setCurrentlyPlayingId(null);
    });
  };

  const handlePreviewNext = async () => {
    try {
      setGenerating(true);
      const res = await fetch("/api/admin/radio/drops", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "preview_next", intro_seconds: 10 }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "Generation failed");

      showFeedback(`✓ Next drop generated by ${data.drop?.persona_name} (${data.drop?.drop_type})!`, "success");
      fetchDrops();
    } catch (err: any) {
      showFeedback("Failed to preview next drop: " + err.message, "error");
    } finally {
      setGenerating(false);
    }
  };

  const handleDelete = async (id: number) => {
    if (!confirm("Are you sure you want to delete this radio drop?")) return;
    try {
      const res = await fetch(`/api/admin/radio/drops?id=${id}`, { method: "DELETE" });
      if (res.ok) {
        setDrops((prev) => prev.filter((d) => d.id !== id));
        showFeedback("Drop deleted successfully", "success");
      }
    } catch (err: any) {
      showFeedback("Delete failed: " + err.message, "error");
    }
  };

  return (
    <div className="space-y-6">
      {/* Header & Controls */}
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 bg-zinc-900 border border-zinc-800 p-4 rounded-xl">
        <div>
          <h2 className="text-lg font-bold text-white flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-amber-400" />
            AI Radio Drops (Last 50 Generated)
          </h2>
          <p className="text-xs text-zinc-400">
            Pre-generated drops grounded on live Neon facts, Drop Gate checked, mastered at -14 LUFS.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={fetchDrops}
            disabled={loading}
            className="px-3 py-2 bg-zinc-800 hover:bg-zinc-700 text-zinc-200 rounded-lg text-xs font-medium flex items-center gap-1.5 transition-colors"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${loading ? "animate-spin" : ""}`} />
            Refresh
          </button>
          <button
            onClick={handlePreviewNext}
            disabled={generating}
            className="px-4 py-2 bg-amber-500 hover:bg-amber-400 text-black font-semibold rounded-lg text-xs flex items-center gap-1.5 transition-colors shadow-lg shadow-amber-500/20"
          >
            <Sparkles className="w-4 h-4" />
            {generating ? "Generating Drop v2..." : "Preview Next Drop"}
          </button>
        </div>
      </div>

      {feedback && (
        <div className={`p-3 rounded-lg text-xs flex items-center gap-2 ${
          feedback.type === "success" ? "bg-emerald-950/60 text-emerald-300 border border-emerald-800" : "bg-red-950/60 text-red-300 border border-red-800"
        }`}>
          {feedback.type === "success" ? <CheckCircle2 className="w-4 h-4" /> : <AlertCircle className="w-4 h-4" />}
          {feedback.text}
        </div>
      )}

      {/* Drops Table / List */}
      <div className="bg-zinc-900 border border-zinc-800 rounded-xl overflow-hidden">
        {loading ? (
          <div className="p-8 text-center text-zinc-500 text-xs">Loading drops history...</div>
        ) : drops.length === 0 ? (
          <div className="p-8 text-center text-zinc-500 text-xs">
            No drops logged yet. Click "Preview Next Drop" above to trigger Drop Engine v2.
          </div>
        ) : (
          <div className="divide-y divide-zinc-800">
            {drops.map((drop) => {
              const isPlaying = currentlyPlayingId === drop.id;
              return (
                <div key={drop.id} className="p-4 hover:bg-zinc-850/50 transition-colors flex flex-col md:flex-row md:items-center justify-between gap-4">
                  <div className="space-y-1.5 flex-1">
                    <div className="flex items-center gap-2 flex-wrap">
                      <span className="font-semibold text-white text-sm">{drop.persona || "Presenter"}</span>
                      <span className="px-2 py-0.5 bg-amber-500/10 border border-amber-500/20 text-amber-400 rounded-full text-[10px] font-mono">
                        {drop.timing_type || "drop"}
                      </span>
                      {drop.mood && (
                        <span className="px-2 py-0.5 bg-zinc-800 text-zinc-400 rounded-full text-[10px] font-mono">
                          {drop.mood}
                        </span>
                      )}
                      <span className="text-[10px] text-zinc-500">
                        {new Date(drop.created_at).toLocaleString("en-KE", { timeZone: "Africa/Nairobi" })}
                      </span>
                    </div>
                    <p className="text-xs text-zinc-300 leading-relaxed font-sans">
                      "{drop.script}"
                    </p>
                  </div>

                  <div className="flex items-center gap-2 self-end md:self-center">
                    {drop.audio_url ? (
                      <button
                        onClick={() => handlePlayToggle(drop)}
                        className={`p-2 rounded-lg text-xs font-medium flex items-center gap-1.5 transition-colors ${
                          isPlaying
                            ? "bg-amber-500 text-black font-semibold"
                            : "bg-zinc-800 hover:bg-zinc-700 text-zinc-200"
                        }`}
                      >
                        {isPlaying ? <Pause className="w-4 h-4" /> : <Play className="w-4 h-4" />}
                        {isPlaying ? "Playing" : "Listen"}
                      </button>
                    ) : (
                      <span className="text-[10px] text-zinc-500 italic px-2">No audio</span>
                    )}

                    <button
                      onClick={() => handleDelete(drop.id)}
                      className="p-2 text-zinc-500 hover:text-red-400 hover:bg-red-950/30 rounded-lg transition-colors"
                      title="Delete drop"
                    >
                      <Trash2 className="w-4 h-4" />
                    </button>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
}
