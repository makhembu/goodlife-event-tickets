"use client";

import React, { useState, useEffect } from "react";
import { Play, Pause, Trash2, RefreshCw, Sparkles, Volume2, CheckCircle2, AlertCircle, Radio, Send } from "lucide-react";
import { useRadio } from "@/context/RadioContext";

interface RadioDropItem {
  id: number;
  persona: string;
  mood: string;
  title: string;
  script: string;
  audio_url: string;
  timing_type: string;
  created_at: string;
}

interface DropManagerPanelProps {
  onSendToCue?: (cueItem: {
    id: string;
    title: string;
    script: string;
    audioUrl: string;
    persona?: string;
  }) => void;
}

export default function DropManagerPanel({ onSendToCue }: DropManagerPanelProps) {
  const { airLiveDrop } = useRadio();
  const [drops, setDrops] = useState<RadioDropItem[]>([]);
  const [firingId, setFiringId] = useState<number | null>(null);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [currentlyPlayingId, setCurrentlyPlayingId] = useState<number | null>(null);
  const [audioElement, setAudioElement] = useState<HTMLAudioElement | null>(null);
  const [feedback, setFeedback] = useState<{ text: string; type: "success" | "error" } | null>(null);

  const showFeedback = (text: string, type: "success" | "error") => {
    setFeedback({ text, type });
    setTimeout(() => setFeedback(null), 4000);
  };

  const fetchDrops = async () => {
    try {
      setLoading(true);
      const res = await fetch("/api/admin/radio/drops");
      if (res.ok) {
        const data = await res.json();
        setDrops(data.drops || []);
      }
    } catch (err: any) {
      showFeedback("Failed to load drops: " + err.message, "error");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchDrops();
  }, []);

  const handlePlayToggle = (drop: RadioDropItem) => {
    if (!drop.audio_url) {
      showFeedback("Audio file not available for this drop (synthesis pending or mock)", "error");
      return;
    }

    if (currentlyPlayingId === drop.id && audioElement) {
      audioElement.pause();
      setCurrentlyPlayingId(null);
      return;
    }

    if (audioElement) {
      audioElement.pause();
    }

    const audio = new Audio(drop.audio_url);
    audio.onended = () => setCurrentlyPlayingId(null);
    audio.onerror = () => {
      showFeedback("Failed to play drop audio", "error");
      setCurrentlyPlayingId(null);
    };

    audio.play().then(() => {
      setAudioElement(audio);
      setCurrentlyPlayingId(drop.id);
    }).catch(() => {
      setCurrentlyPlayingId(null);
    });
  };

  const handlePreviewNext = async () => {
    try {
      setGenerating(true);
      const res = await fetch("/api/admin/radio/drops", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "preview_next", intro_seconds: 10 }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "Generation failed");

      showFeedback(`✓ Next drop generated by ${data.drop?.persona_name} (${data.drop?.drop_type})!`, "success");
      fetchDrops();
    } catch (err: any) {
      showFeedback("Failed to preview next drop: " + err.message, "error");
    } finally {
      setGenerating(false);
    }
  };

  const handleDelete = async (id: number) => {
    if (!confirm("Are you sure you want to delete this radio drop?")) return;
    try {
      const res = await fetch(`/api/admin/radio/drops?id=${id}`, { method: "DELETE" });
      if (res.ok) {
        setDrops((prev) => prev.filter((d) => d.id !== id));
        showFeedback("Drop deleted successfully", "success");
      }
    } catch (err: any) {
      showFeedback("Delete failed: " + err.message, "error");
    }
  };

  return (
    <div className="space-y-6">
      {/* Header & Controls */}
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 bg-[#16181D] text-[#FBF9F6] border-2 border-[#16181D] p-4 shadow-[4px_4px_0px_#DFBB7D]">
        <div>
          <h2 className="text-base font-bold font-mono uppercase tracking-wider text-white flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-[#DFBB7D]" />
            AI Radio Drops (Last 50 Generated)
          </h2>
          <p className="text-xs text-[#DFBB7D] font-mono mt-0.5">
            Pre-generated drops grounded on live Neon facts, Drop Gate checked, mastered at -14 LUFS.
          </p>
        </div>

        <div className="flex items-center gap-2 font-mono">
          <button
            onClick={fetchDrops}
            disabled={loading}
            className="px-3.5 py-1.5 bg-[#1A1D24] hover:bg-white/10 text-white border border-white/20 text-xs font-bold uppercase flex items-center gap-1.5 transition-all cursor-pointer"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${loading ? "animate-spin text-[#DFBB7D]" : ""}`} />
            Refresh
          </button>
          <button
            onClick={handlePreviewNext}
            disabled={generating}
            className="px-4 py-1.5 bg-[#DFBB7D] hover:bg-[#F5C842] text-[#16181D] font-bold text-xs uppercase border border-[#16181D] shadow-[2px_2px_0px_#16181D] flex items-center gap-1.5 transition-all active:scale-95 cursor-pointer"
          >
            <Sparkles className="w-4 h-4" />
            {generating ? "Generating Drop v2..." : "Preview Next Drop"}
          </button>
        </div>
      </div>

      {feedback && (
        <div className={`p-3 font-mono text-xs flex items-center gap-2 border ${
          feedback.type === "success" ? "bg-emerald-950/80 text-emerald-300 border-emerald-600" : "bg-red-950/80 text-red-300 border-red-600"
        }`}>
          {feedback.type === "success" ? <CheckCircle2 className="w-4 h-4" /> : <AlertCircle className="w-4 h-4" />}
          {feedback.text}
        </div>
      )}

      {/* Drops Table / List */}
      <div className="bg-[#16181D] text-[#FBF9F6] border-2 border-[#16181D] shadow-[4px_4px_0px_#DFBB7D] overflow-hidden">
        {loading ? (
          <div className="p-8 text-center text-white/50 font-mono text-xs">Loading drops history...</div>
        ) : drops.length === 0 ? (
          <div className="p-8 text-center text-white/60 font-mono text-xs">
            No drops logged yet. Click "Preview Next Drop" above to trigger Drop Engine v2.
          </div>
        ) : (
          <div className="divide-y divide-white/10">
            {drops.map((drop) => {
              const isPlaying = currentlyPlayingId === drop.id;
              return (
                <div key={drop.id} className="p-4 hover:bg-white/5 transition-colors flex flex-col md:flex-row md:items-center justify-between gap-4 font-mono">
                  <div className="space-y-1.5 flex-1 min-w-0">
                    <div className="flex items-center gap-2 flex-wrap">
                      <span className="font-bold text-white text-sm">{drop.persona || "Presenter"}</span>
                      <span className="px-2 py-0.5 bg-[#DFBB7D] text-[#16181D] text-[10px] font-bold uppercase border border-[#16181D]">
                        {drop.timing_type || "drop"}
                      </span>
                      {drop.mood && (
                        <span className="px-2 py-0.5 bg-black/40 text-white/80 border border-white/20 text-[10px] font-bold uppercase">
                          {drop.mood}
                        </span>
                      )}
                      <span className="text-[11px] text-[#DFBB7D] font-bold">
                        {new Date(drop.created_at).toLocaleString("en-KE", { timeZone: "Africa/Nairobi" })}
                      </span>
                    </div>
                    <p className="text-xs text-white leading-relaxed font-sans bg-[#121316] p-2.5 border border-white/10">
                      "{drop.script}"
                    </p>
                  </div>

                  <div className="flex flex-wrap items-center gap-2 self-end md:self-center shrink-0">
                    {drop.audio_url ? (
                      <>
                        <button
                          onClick={() => handlePlayToggle(drop)}
                          className={`px-3 py-1.5 text-xs font-bold uppercase flex items-center gap-1.5 transition-all border cursor-pointer ${
                            isPlaying
                              ? "bg-red-600 text-white border-red-500 font-bold"
                              : "bg-[#DFBB7D] hover:bg-[#F5C842] text-[#16181D] border-[#16181D] shadow-[2px_2px_0px_#16181D]"
                          }`}
                        >
                          {isPlaying ? <Pause className="w-3.5 h-3.5" /> : <Play className="w-3.5 h-3.5" />}
                          {isPlaying ? "Playing" : "Listen"}
                        </button>
                        {onSendToCue && (
                          <button
                            onClick={() => {
                              onSendToCue({
                                id: `drop_${drop.id}`,
                                title: drop.title || `${drop.persona || "Station"} Drop`,
                                script: drop.script,
                                audioUrl: drop.audio_url,
                                persona: drop.persona,
                              });
                              showFeedback(`Loaded "${drop.persona || "Drop"}" into Studio Cue Dock`, "success");
                            }}
                            className="px-2.5 py-1.5 text-xs font-bold uppercase flex items-center gap-1.5 bg-[#1A1D24] hover:bg-white/10 text-[#DFBB7D] border border-[#DFBB7D]/50 transition-all cursor-pointer"
                            title="Send drop to Studio Deck A Cue Dock"
                          >
                            <Send className="w-3.5 h-3.5" />
                            <span>Send to Cue</span>
                          </button>
                        )}
                        <button
                          disabled={firingId === drop.id}
                          onClick={async () => {
                            if (firingId === drop.id) return;
                            setFiringId(drop.id);
                            try {
                              const ok = await airLiveDrop({
                                audioUrl: drop.audio_url,
                                title: drop.title || "Station Drop",
                                persona: drop.persona || "GOODLIFE Radio",
                                script: drop.script,
                              });
                              showFeedback(
                                ok
                                  ? `🔴 "${drop.persona || "Drop"}" FIRED ON AIR live!`
                                  : "Failed to broadcast drop live",
                                ok ? "success" : "error"
                              );
                            } finally {
                              setFiringId(null);
                            }
                          }}
                          className="px-2.5 py-1.5 text-xs font-bold uppercase flex items-center gap-1.5 bg-[#E84855] hover:bg-red-500 text-white border border-red-400/50 transition-all cursor-pointer disabled:opacity-50"
                          title="Fire drop immediately across live stream"
                        >
                          <Radio className="w-3.5 h-3.5" />
                          <span>{firingId === drop.id ? "Airing..." : "Fire On Air"}</span>
                        </button>
                      </>
                    ) : (
                      <span className="text-[10px] text-white/40 italic px-2">No audio</span>
                    )}

                    <button
                      onClick={() => handleDelete(drop.id)}
                      className="p-1.5 text-white/40 hover:text-red-400 hover:bg-red-950/40 border border-transparent hover:border-red-500/30 transition-colors cursor-pointer"
                      title="Delete drop"
                    >
                      <Trash2 className="w-4 h-4" />
                    </button>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
}
